pub fn terminal_palette_by_id(id: &str) -> Option<&'static TerminalPalette> {
    PALETTES.iter().find(|palette| palette.id == id)
}

pub fn default_terminal_palette() -> &'static TerminalPalette {
    crate::config::read_value("terminal_palette")
        .and_then(|id| terminal_palette_by_id(&id))
        .unwrap_or_else(|| {
            terminal_palette_by_id(DEFAULT_TERMINAL_PALETTE_ID).expect("default terminal palette")
        })
}

pub fn set_default_terminal_palette(id: &str) {
    crate::config::write_value("terminal_palette", id);
}

pub fn primary_terminal_palettes() -> impl Iterator<Item = &'static TerminalPalette> {
    PALETTES.iter().filter(|palette| palette.primary)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serial_test::serial;
    use std::time::{SystemTime, UNIX_EPOCH};

    #[test]
    fn palette_table_keeps_ptyxis_primary_subset() {
        let names = primary_terminal_palettes()
            .map(|palette| palette.name)
            .collect::<Vec<_>>();

        assert_eq!(
            names,
            [
                "Campbell",
                "Dracula",
                "GNOME",
                "High Contrast",
                "Horizon",
                "Linux",
                "Nord",
                "Solarized",
                "Tango",
                "VS Code",
                "XTerm",
            ]
        );
    }

    #[test]
    fn palette_table_contains_expanded_ptyxis_palettes() {
        assert!(PALETTES.len() > 200);
        assert_eq!(
            terminal_palette_by_id("3024").map(|palette| palette.name),
            Some("3024")
        );
        assert_eq!(
            terminal_palette_by_id("Aci").map(|palette| palette.name),
            Some("Aci")
        );
        assert_eq!(
            terminal_palette_by_id("Blazer").map(|palette| palette.name),
            Some("Blazer")
        );
    }

    #[test]
    #[serial]
    fn default_palette_uses_configured_palette_with_gnome_fallback() {
        let dir = std::env::temp_dir().join(format!(
            "chelotype-terminal-palette-config-{}",
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .expect("system time")
                .as_nanos()
        ));
        unsafe {
            std::env::set_var("CHELOTYPE_CONFIG_DIR", &dir);
        }

        assert_eq!(default_terminal_palette().id, DEFAULT_TERMINAL_PALETTE_ID);
        set_default_terminal_palette("dracula");
        assert_eq!(default_terminal_palette().name, "Dracula");
        crate::config::write_value("terminal_palette", "missing");
        assert_eq!(default_terminal_palette().id, DEFAULT_TERMINAL_PALETTE_ID);

        unsafe {
            std::env::remove_var("CHELOTYPE_CONFIG_DIR");
        }
        let _ = std::fs::remove_dir_all(dir);
    }
}
